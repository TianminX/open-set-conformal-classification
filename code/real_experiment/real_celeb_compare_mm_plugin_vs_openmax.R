# ============================================================
# Compare, on CelebA, the plug-in missing-mass method
#     results_hpc/celeb_mm_plugin/  (real_experiment_celeb_mm_plugin.py)
# against direct conformalization of off-the-shelf OpenMax classifiers
#     results_hpc/celeb_openmax/    (real_experiment_celeb_openmax.py)
#
# Diagnostic figure: four panels vs n_ref
#   1) Coverage            - each method at ITS OWN nominal level:
#        CGTC+: `Coverage (?)`           (joker credited only for labels
#                                             outside the whole reference set)
#        OpenMax:   `Coverage (joker_train)` (joker credited for any label
#                                             outside the training set - the
#                                             event direct conformalization
#                                             is valid for)
#   2) Set Size (Raw)      - raw size excluding "?" (as produced)
#   3) Prediction Set Size - open-set size with "?" charged the number of
#        calibration-only classes, i.e. the DECODED size (the CGTC+ sets
#        enumerate those classes explicitly, so this puts both on the same
#        footing; CGTC+ is identical in panels 2 and 3).
#   4) Joker Proportion
# Paper figure: panels 1, 3, 4 only, legend on the right.
#
# OpenMax uses ONLY the random internal split: the Bernoulli selective split
# without the weighted-quantile correction has no exact coverage guarantee
# (get_prediction_sets_openmax_bernoulli uses the unweighted quantile).
# ============================================================

