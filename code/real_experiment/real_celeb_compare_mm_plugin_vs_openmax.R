#                           similar to the simplified OpenMax, adds clutter).
#   "mm_vs_recal"  (Fig 2): Naive baseline + Recal-KNN-dist (collapses onto
#                           the naive baseline) + Recal-PROSER (improves on it
#                           at small n_ref, keeps unseen coverage at large)
#                           + Recal-OCC (CGTC's own ranking; the strongest
#                           recalibrated benchmark).
# "random" keeps every family for diagnostics.
