# selective-split method (valid thanks to the weighted-quantile correction).
# Per-setting inclusion flags (each family also needs its results folder):
#   om_variants        - simplified OpenMax variants ("KNN"/"MLP"; empty = none)
#   osdn               - OpenMax (faithful), the MLP-based OSDN configuration
#   recal_openmax      - GT-recalibrated OpenMax (follows om_variants)
#   raw_knn_scores     - raw KNN-dist / KNN-MSP
