# ============================================================
# One full comparison (all plots + diff table) for a split setting
# ============================================================
run_comparison <- function(split_name, mm_method_row, flag, openmax_bernoulli,
                           om_variants, osdn, recal_openmax, raw_knn_scores,
                           recal_knn_variants, gt_knn, proser, proser_recal,
                           occ_recal) {
  # tribble list-column cells arrive wrapped in a length-1 list; unwrap so
  # the variant selectors are plain character vectors (possibly empty).
  om_variants <- unlist(om_variants)
  recal_knn_variants <- unlist(recal_knn_variants)
  cat(sprintf("\n########## split = %s (plug-in row: %s, flag = %d; OpenMax bernoulli = %s; variants: %s) ##########\n",
              split_name, mm_method_row, flag, openmax_bernoulli,
              paste(om_variants, collapse = ", ")))

  om_prefix <- if (openmax_bernoulli) "Method (Bernoulli OpenMax-" else "Method (OpenMax-"
  om_rows <- if (length(om_variants) > 0) paste0(om_prefix, om_variants, ")") else character(0)
  # Recalibrated OpenMax follows the same variant selection (random split only)
  recal_rows <- if (length(om_variants) > 0)
    paste0("Method (Recal OpenMax-", om_variants, ")") else character(0)

  df_mm <- df_mm_all %>% filter(splitting_method_flag == flag)
  df_om <- df_om_all %>% filter(method %in% om_rows)
  # Faithful-OSDN OpenMax: only the MLP configuration is shown in figures.
  df_osdn <- if (!osdn || is.null(df_osdn_all)) NULL else
    df_osdn_all %>% filter(method == "Method (OpenMax-MLP)")
  n_osdn <- if (is.null(df_osdn)) 0 else nrow(df_osdn)
  df_recal <- if (!recal_openmax || is.null(df_recal_all)) NULL else
    df_recal_all %>% filter(method %in% recal_rows)
  n_recal <- if (is.null(df_recal)) 0 else nrow(df_recal)
  n_gt <- if (!gt_knn || is.null(df_gt_all)) 0 else nrow(df_gt_all)
  recal_knn_rows <- if (length(recal_knn_variants) > 0)
    paste0("Method (Recal KNN-", recal_knn_variants, ")") else character(0)
  df_knnsc <- if (length(recal_knn_rows) == 0 || is.null(df_knnsc_all)) NULL else
    df_knnsc_all %>% filter(method %in% recal_knn_rows)
  n_knnsc <- if (is.null(df_knnsc)) 0 else nrow(df_knnsc)
  n_knnraw <- if (!raw_knn_scores || is.null(df_knnraw_all)) 0 else nrow(df_knnraw_all)
  # PROSER is a raw (non-recalibrated) baseline. It has its own inclusion flag
  # so it can be shown on its own (the mm_vs_proser figure).
  n_proser <- if (!proser || is.null(df_proser_all)) 0 else nrow(df_proser_all)
  n_proser_recal <- if (!proser_recal || is.null(df_proser_recal_all)) 0 else
    nrow(df_proser_recal_all)
  # Recal-OCC only (the raw OCC rows appear in the benchmark table, not the
  # figures).
  df_occ <- if (!occ_recal || is.null(df_occ_all)) NULL else
    df_occ_all %>% filter(method == "Method (Recal OCC)")
  n_occ <- if (is.null(df_occ)) 0 else nrow(df_occ)
  cat("  mm_plugin rows:", nrow(df_mm), " | OpenMax rows:", nrow(df_om),
      " | OSDN rows:", n_osdn, " | Recal rows:", n_recal,
      " | KNN-score rows:", n_knnsc, " | raw KNN-score rows:", n_knnraw,
      " | PROSER rows:", n_proser, " | Recal-PROSER rows:", n_proser_recal,
      " | Recal-OCC rows:", n_occ, " | Naive rows:", n_gt, "\n")
  if (nrow(df_mm) == 0 ||
      (nrow(df_om) == 0 && n_osdn == 0 && n_recal == 0 && n_knnsc == 0 &&
       n_knnraw == 0 && n_proser == 0 && n_proser_recal == 0 && n_occ == 0 &&
       n_gt == 0)) {
    warning("No rows for split '", split_name, "'; skipping this setting.",
            call. = FALSE)
    return(invisible(NULL))
  }

  # ---- common n_ref (intersection over the sources present) ----------------
  nref_sets <- list(unique(df_mm$n_ref))
  if (nrow(df_om) > 0) nref_sets <- c(nref_sets, list(unique(df_om$n_ref)))
  if (n_osdn > 0)      nref_sets <- c(nref_sets, list(unique(df_osdn$n_ref)))
  if (n_recal > 0)     nref_sets <- c(nref_sets, list(unique(df_recal$n_ref)))
  if (n_knnsc > 0)     nref_sets <- c(nref_sets, list(unique(df_knnsc$n_ref)))
  if (n_knnraw > 0)    nref_sets <- c(nref_sets, list(unique(df_knnraw_all$n_ref)))
  if (n_proser > 0)    nref_sets <- c(nref_sets, list(unique(df_proser_all$n_ref)))
  if (n_proser_recal > 0)
    nref_sets <- c(nref_sets, list(unique(df_proser_recal_all$n_ref)))
  if (n_occ > 0)       nref_sets <- c(nref_sets, list(unique(df_occ$n_ref)))
  if (n_gt > 0)        nref_sets <- c(nref_sets, list(unique(df_gt_all$n_ref)))
  common_nref <- sort(Reduce(intersect, nref_sets))
  cat("  common n_ref:", paste(common_nref, collapse = ", "), "\n")
  if (length(common_nref) == 0) {
    warning("No overlapping n_ref between the two result folders for split '",
            split_name, "'; skipping.", call. = FALSE)
    return(invisible(NULL))
  }

  # Plug-in rows: reference-level coverage (its nominal guarantee); set size
  # EXCLUDES "?" and already enumerates calibration-only classes explicitly,
  # so raw and joker-adjusted sizes coincide.
  prep_mm <- function(df) {
    df %>%
      filter(method == mm_method_row, pvalue_method == PVAL,
             abs(alpha_total - ALPHA_TOT) < 1e-10,
             abs(lambda_weight - LAMBDA) < 1e-10,
             n_label_total == NLABEL, k_top == KTOP, k_bot == KBOT,
             n_ref %in% common_nref) %>%
      transmute(
        n_ref, batch_num,
        cov_marginal = `Coverage (?)`,
        cov_seen     = `Seen Coverage (?)`,
        cov_unseen   = `Unseen Coverage (?)`,
        size_raw     = Size,
        size_adj     = Size,
        prop_joker   = `Prop ?`,
        prop_unseen  = prop_unseen_test,
        source = "CGTC+")
  }

  # OpenMax rows: train-level coverage throughout (the event the direct
  # method's conformal guarantee applies to; reference-level coverage is not
  # meaningful for it because its sets can never name calibration-only
  # labels). Seen/unseen groups are relative to the TRAINING set here.
  prep_om <- function(df) {
    df %>%
      filter(method %in% om_rows,
             abs(alpha_total - ALPHA_TOT) < 1e-10,
             n_label_total == NLABEL, k_top == KTOP, k_bot == KBOT,
             n_ref %in% common_nref) %>%
      transmute(
        n_ref, batch_num,
        cov_marginal = `Coverage (joker_train)`,
        cov_seen     = `Seen Coverage (joker_train)`,
        cov_unseen   = `Unseen Coverage (joker_train)`,
        size_raw     = Size,
        size_adj     = `Size (joker_adj)`,
        prop_joker   = `Prop ?`,
        prop_unseen  = prop_unseen_test,
        source = ifelse(grepl("KNN", method), "OpenMax-KNN",
                        "OpenMax (simplified)"))
  }

  # Faithful-OSDN OpenMax rows: same family and scoring as the simplified
  # OpenMax rows (train-level coverage, decoded size).
  prep_osdn <- function(df) {
    df %>%
      filter(abs(alpha_total - ALPHA_TOT) < 1e-10,
             n_label_total == NLABEL, k_top == KTOP, k_bot == KBOT,
             n_ref %in% common_nref) %>%
      transmute(
        n_ref, batch_num,
        cov_marginal = `Coverage (joker_train)`,
        cov_seen     = `Seen Coverage (joker_train)`,
        cov_unseen   = `Unseen Coverage (joker_train)`,
        size_raw     = Size,
        size_adj     = `Size (joker_adj)`,
        prop_joker   = `Prop ?`,
        prop_unseen  = prop_unseen_test,
        source = "OpenMax (faithful)")
  }

  # Naive-baseline rows (GT-constant KNN, CSV row "Method (GT-KNN)"): same
  # direct-conformalization family as OpenMax
  # (K+1 probabilities, unknown column = constant Good-Turing estimate), so
  # it is scored the same way (train-level coverage, joker-adjusted size).
  prep_gt <- function(df) {
    df %>%
      filter(method == "Method (GT-KNN)",
             abs(alpha_total - ALPHA_TOT) < 1e-10,
             n_label_total == NLABEL, k_top == KTOP, k_bot == KBOT,
             n_ref %in% common_nref) %>%
      transmute(
        n_ref, batch_num,
        cov_marginal = `Coverage (joker_train)`,
        cov_seen     = `Seen Coverage (joker_train)`,
        cov_unseen   = `Unseen Coverage (joker_train)`,
        size_raw     = Size,
        size_adj     = `Size (joker_adj)`,
        prop_joker   = `Prop ?`,
        prop_unseen  = prop_unseen_test,
        source = "Naive")
  }

  # Recalibrated OpenMax rows: same family and scoring as the raw OpenMax rows.
  prep_recal <- function(df) {
    df %>%
      filter(method %in% recal_rows,
             abs(alpha_total - ALPHA_TOT) < 1e-10,
             n_label_total == NLABEL, k_top == KTOP, k_bot == KBOT,
             n_ref %in% common_nref) %>%
      transmute(
        n_ref, batch_num,
        cov_marginal = `Coverage (joker_train)`,
        cov_seen     = `Seen Coverage (joker_train)`,
        cov_unseen   = `Unseen Coverage (joker_train)`,
        size_raw     = Size,
        size_adj     = `Size (joker_adj)`,
        prop_joker   = `Prop ?`,
        prop_unseen  = prop_unseen_test,
        source = ifelse(grepl("KNN", method),
                        "Recal-OpenMax-KNN", "Recal-OpenMax"))
  }

  # GT-recal KNN-score rows (KNN-dist / KNN-MSP): same family and scoring as
  # the other direct-conformalization rows. Included whenever present, like
  # the Naive baseline.
  prep_knnsc <- function(df) {
    df %>%
      filter(method %in% recal_knn_rows,
             abs(alpha_total - ALPHA_TOT) < 1e-10,
             n_label_total == NLABEL, k_top == KTOP, k_bot == KBOT,
             n_ref %in% common_nref) %>%
      transmute(
        n_ref, batch_num,
        cov_marginal = `Coverage (joker_train)`,
        cov_seen     = `Seen Coverage (joker_train)`,
        cov_unseen   = `Unseen Coverage (joker_train)`,
        size_raw     = Size,
        size_adj     = `Size (joker_adj)`,
        prop_joker   = `Prop ?`,
        prop_unseen  = prop_unseen_test,
        source = ifelse(grepl("dist", method),
                        "Recal-KNN-dist", "Recal-KNN-MSP"))
  }

  # Raw (non-recalibrated) KNN-score rows: same scoring, no GT anchoring.
  prep_knnraw <- function(df) {
    df %>%
      filter(method %in% c("Method (KNN-dist)", "Method (KNN-MSP)"),
             abs(alpha_total - ALPHA_TOT) < 1e-10,
             n_label_total == NLABEL, k_top == KTOP, k_bot == KBOT,
             n_ref %in% common_nref) %>%
      transmute(
        n_ref, batch_num,
        cov_marginal = `Coverage (joker_train)`,
        cov_seen     = `Seen Coverage (joker_train)`,
        cov_unseen   = `Unseen Coverage (joker_train)`,
        size_raw     = Size,
        size_adj     = `Size (joker_adj)`,
        prop_joker   = `Prop ?`,
        prop_unseen  = prop_unseen_test,
        source = ifelse(grepl("dist", method), "KNN-dist", "KNN-MSP"))
  }

  # Raw PROSER rows: same scoring as the other direct-conformalization rows.
  prep_proser <- function(df) {
    df %>%
      filter(method == "Method (PROSER)",
             abs(alpha_total - ALPHA_TOT) < 1e-10,
             n_label_total == NLABEL, k_top == KTOP, k_bot == KBOT,
             n_ref %in% common_nref) %>%
      transmute(
        n_ref, batch_num,
        cov_marginal = `Coverage (joker_train)`,
        cov_seen     = `Seen Coverage (joker_train)`,
        cov_unseen   = `Unseen Coverage (joker_train)`,
        size_raw     = Size,
        size_adj     = `Size (joker_adj)`,
        prop_joker   = `Prop ?`,
        prop_unseen  = prop_unseen_test,
        source = "PROSER")
  }

  # GT-recal PROSER rows: same scoring as the other recalibrated rows.
  prep_proser_recal <- function(df) {
    df %>%
      filter(method == "Method (Recal PROSER)",
             abs(alpha_total - ALPHA_TOT) < 1e-10,
             n_label_total == NLABEL, k_top == KTOP, k_bot == KBOT,
             n_ref %in% common_nref) %>%
      transmute(
        n_ref, batch_num,
        cov_marginal = `Coverage (joker_train)`,
        cov_seen     = `Seen Coverage (joker_train)`,
        cov_unseen   = `Unseen Coverage (joker_train)`,
        size_raw     = Size,
        size_adj     = `Size (joker_adj)`,
        prop_joker   = `Prop ?`,
        prop_unseen  = prop_unseen_test,
        source = "Recal-PROSER")
  }

  # GT-recal OCC rows: same scoring as the other recalibrated rows.
  prep_occ_recal <- function(df) {
    df %>%
      filter(abs(alpha_total - ALPHA_TOT) < 1e-10,
             n_label_total == NLABEL, k_top == KTOP, k_bot == KBOT,
             n_ref %in% common_nref) %>%
      transmute(
        n_ref, batch_num,
        cov_marginal = `Coverage (joker_train)`,
        cov_seen     = `Seen Coverage (joker_train)`,
        cov_unseen   = `Unseen Coverage (joker_train)`,
        size_raw     = Size,
        size_adj     = `Size (joker_adj)`,
        prop_joker   = `Prop ?`,
        prop_unseen  = prop_unseen_test,
        source = "Recal-OCC")
  }

  dat <- bind_rows(
    prep_mm(df_mm),
    if (nrow(df_om) > 0) prep_om(df_om),
    if (n_osdn > 0) prep_osdn(df_osdn),
    if (n_recal > 0) prep_recal(df_recal),
    if (n_knnraw > 0) prep_knnraw(df_knnraw_all),
    if (n_proser > 0) prep_proser(df_proser_all),
    if (n_proser_recal > 0) prep_proser_recal(df_proser_recal_all),
    if (n_occ > 0) prep_occ_recal(df_occ),
    if (n_knnsc > 0) prep_knnsc(df_knnsc),
    if (n_gt > 0) prep_gt(df_gt_all)
  ) %>%
    mutate(source = factor(source, levels = source_levels))

  if (nrow(dat) == 0) {
    warning("No rows match the selected knobs for split '", split_name,
            "'. Check method rows / filters; skipping.", call. = FALSE)
    return(invisible(NULL))
  }

  # mean +/- se across batches, per n_ref x source
  se <- function(x) sd(x, na.rm = TRUE) / sqrt(sum(!is.na(x)))
  agg <- dat %>%
    group_by(n_ref, source) %>%
    summarise(across(c(cov_marginal, cov_seen, cov_unseen,
                       size_raw, size_adj, prop_joker, prop_unseen),
                     list(m = ~mean(.x, na.rm = TRUE), se = ~se(.x)),
                     .names = "{.col}.{.fn}"),
              .groups = "drop")

  out_file <- function(stem)
    sprintf("real_celeb_mm_plugin_vs_openmax_%s_%s.pdf", stem, split_name)

  # ============================================================
  # Plot 1: coverage vs n_ref (marginal / seen / unseen, nominal level each)
  # ============================================================
  cov_long <- agg %>%
    select(n_ref, source, starts_with("cov_marginal"),
           starts_with("cov_seen"), starts_with("cov_unseen")) %>%
    pivot_longer(-c(n_ref, source),
                 names_to = c("metric", ".value"), names_sep = "\\.") %>%
    mutate(metric = recode(metric,
      cov_marginal = "Marginal", cov_seen = "Seen", cov_unseen = "Unseen") %>%
      factor(levels = c("Marginal", "Seen", "Unseen")))

  p_cov <- ggplot(cov_long, aes(n_ref, m, color = source, fill = source)) +
    geom_hline(yintercept = 1 - ALPHA_TOT, linetype = "dashed", color = "grey40") +
    geom_errorbar(aes(ymin = m - 1.96 * se, ymax = m + 1.96 * se), width = 150) +
    geom_line() + geom_point(size = 1.2) +
    facet_wrap(~ metric) +
    scale_color_manual(values = source_colors) +
    scale_fill_manual(values = source_colors) +
    labs(x = "Number of reference observations (n_ref)", y = "Coverage",
         color = NULL, fill = NULL,
         title = sprintf("CelebA coverage vs n_ref: CGTC+ vs conformalized OpenMax (%s)",
                         split_name),
         caption = "CGTC+ scored at the reference level (Coverage (?)); OpenMax at its nominal training level (Coverage (joker_train)).\nSeen/unseen groups: relative to the reference set for CGTC+, to the training set for OpenMax.") +
    theme_cmp

  ggsave(out_file("coverage"), p_cov, width = 10, height = 4)
  cat(">>> wrote", out_file("coverage"), "\n")

  # ============================================================
  # Plot 2: Coverage | Set Size (Raw) | Prediction Set Size | Joker Proportion
  # ============================================================
  # "Prediction Set Size" is the comparable size: CGTC+'s set size already
  # excludes the joker symbol and names calibration-only labels explicitly,
  # while each open-set method contributes its DECODED size (the bundled '?'
  # charged the number of calibration-only classes). "Set Size (Raw)" keeps
  # the un-decoded benchmark size for diagnostics only.
  metric_levels <- c("Coverage", "Set Size (Raw)", "Prediction Set Size",
                     "Joker Proportion")

  size_long <- bind_rows(
    agg %>% transmute(n_ref, source, metric = "Coverage",
                      m = cov_marginal.m, se = cov_marginal.se),
    agg %>% transmute(n_ref, source, metric = "Set Size (Raw)",
                      m = size_raw.m, se = size_raw.se),
    agg %>% transmute(n_ref, source, metric = "Prediction Set Size",
                      m = size_adj.m, se = size_adj.se),
    agg %>% transmute(n_ref, source, metric = "Joker Proportion",
                      m = prop_joker.m, se = prop_joker.se)
  ) %>%
    mutate(metric = factor(metric, levels = metric_levels))

  # Reference line: true prop. of unseen test labels, joker panel only
  ref_joker <- agg %>%
    group_by(n_ref) %>%
    summarise(m = mean(prop_unseen.m, na.rm = TRUE), .groups = "drop") %>%
    mutate(metric = factor("Joker Proportion", levels = metric_levels))

  # Reference line: nominal coverage target 1 - alpha, Coverage panel only
  cov_target <- tibble(metric = factor("Coverage", levels = metric_levels),
                       yintercept = 1 - ALPHA_TOT)

  p_size <- ggplot(size_long, aes(n_ref, m, color = source, fill = source)) +
    geom_errorbar(aes(ymin = m - 1.96 * se, ymax = m + 1.96 * se), width = 150) +
    geom_line() + geom_point(size = 1.2) +
    geom_hline(data = cov_target, aes(yintercept = yintercept),
               linetype = "dotted", color = "black") +
    geom_line(data = ref_joker, aes(n_ref, m), inherit.aes = FALSE,
              linetype = "dashed", color = "grey40") +
    facet_wrap(~ metric, scales = "free_y", nrow = 1) +
    scale_color_manual(values = source_colors) +
    scale_fill_manual(values = source_colors) +
    labs(x = "Number of reference observations (n_ref)", y = NULL,
         color = NULL, fill = NULL,
         title = sprintf("CelebA: CGTC+ vs conformalized OpenMax  (%s)", split_name),
         caption = paste("Coverage: CGTC+ at the reference level, OpenMax at its nominal training level.",
                         "Set Size (Raw): excl. '?', un-decoded; Prediction Set Size: open-set '?' charged the number of calibration-only classes (decoded), CGTC+ unchanged.",
                         "dotted line = 1 - alpha; dashed line = true prop. of test labels unseen in reference",
                         sep = "\n")) +
    theme_cmp

  ggsave(out_file("size_joker"), p_size, width = 14, height = 4)
  cat(">>> wrote", out_file("size_joker"), "\n")

  # Plot 2 (paper version): three panels only (Coverage | Prediction Set
  # Size | Joker Proportion). The size panel is the comparable one: CGTC+'s
  # own size vs the open-set methods' decoded size.
  size_long_paper <- size_long %>%
    filter(metric != "Set Size (Raw)") %>%
    mutate(metric = droplevels(metric))

  p_size_paper <- ggplot(size_long_paper,
                         aes(n_ref, m, color = source, fill = source,
                             shape = source)) +
    geom_errorbar(aes(ymin = m - 1.96 * se, ymax = m + 1.96 * se),
                  width = 150, linewidth = 0.7) +
    geom_line(linewidth = 0.8) + geom_point(size = 2) +
    geom_hline(data = cov_target, aes(yintercept = yintercept),
               linetype = "dotted", color = "black") +
    geom_line(data = ref_joker, aes(n_ref, m), inherit.aes = FALSE,
              linetype = "dashed", color = "grey40") +
    facet_wrap(~ metric, scales = "free_y", nrow = 1) +
    facetted_pos_scales(y = list(
      metric == "Coverage" ~ scale_y_continuous(limits = c(0, 1)))) +
    scale_shape_manual(values = source_shapes) +
    scale_color_manual(values = source_colors) +
    scale_fill_manual(values = source_colors) +
    labs(x = "Number of reference observations", y = NULL,
         color = NULL, fill = NULL, shape = NULL) +
    theme_paper +
    theme(legend.position = "right")

  ggsave(out_file("size_joker_paper"), p_size_paper, width = 13, height = 3.5)
  cat(">>> wrote", out_file("size_joker_paper"), "\n")

  # ============================================================
  # Console table of differences (OpenMax - CGTC+)
  # ============================================================
  mm <- agg %>% filter(source == "CGTC+") %>%
    select(n_ref, cov_mm = cov_marginal.m, size_mm = size_adj.m,
           joker_mm = prop_joker.m)

  diff_tbl <- agg %>%
    filter(source != "CGTC+") %>%
    select(n_ref, source, cov_marginal.m, size_raw.m, size_adj.m,
           prop_joker.m) %>%
    left_join(mm, by = "n_ref") %>%
    mutate(
      d_cov   = cov_marginal.m - cov_mm,   # note: different nominal levels
      d_size  = size_adj.m - size_mm,
      d_joker = prop_joker.m - joker_mm) %>%
    select(n_ref, source, d_cov, d_size, d_joker,
           om_size_raw = size_raw.m, om_size_adj = size_adj.m)

  cat(sprintf("\n=== Differences (OpenMax - CGTC+), split = %s ===\n", split_name))
  cat("(d_cov compares each method at its own nominal level)\n")
  print(as.data.frame(diff_tbl), digits = 4)

  invisible(agg)
}

