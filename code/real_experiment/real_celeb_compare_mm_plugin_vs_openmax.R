read_dir <- function(path) {
  files <- list.files(path, pattern = "\\.csv$", full.names = TRUE)
  if (length(files) == 0)
    stop("No CSV files found in ", path, ". Run the experiment / download results first.")
  map_dfr(files, ~ {
    dt <- fread(.x)
    dt[, which(!duplicated(names(dt))), with = FALSE]
  })
}

